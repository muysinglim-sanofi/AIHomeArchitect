// Wave 4.9.1b — Perceived-latency UX.
// Phases are an ORDERED architectural narrative (not a cycling loop). The
// scheduler advances through them once with widening, slightly-jittered dwell
// windows and then HOLDS the final phase for the remainder of the 40–90s
// generation — so the experience always reads as "progressing → confidently
// finalizing", never "looping / did it crash". Slot index 3 is the
// atmosphere-flavoured beat (see _atmospherePhase).
const _initialPhrases = [
  'Reading your space…',
  'Preserving the architecture…',
  'Studying natural light and openings…',
  'Composing materials and palette…',     // ← atmosphere-flavoured slot (3)
  'Balancing realism and proportion…',
  'Refining the composition…',
  'Finalizing your vision…',              // ← held to completion
];

const _refinementPhrases = [
  'Revisiting the current design…',
  'Holding the architecture steady…',
  'Applying your direction…',
  'Evolving materials and light…',        // ← atmosphere-flavoured slot (3)
  'Balancing realism and depth…',
  'Refining the details…',
  'Finalizing your vision…',              // ← held to completion
];

// Subtle, single atmosphere-flavoured beat (Task 5). Premium architectural
// tone — deliberately understated, no "AI poetry". Falls back to the generic
// slot-3 phrase when the atmosphere is unknown/absent (resilient — Task 8).
const _atmosphereFlavor = <String, String>{
  'soft luxury': 'Layering warmth, softness, and quiet luxury…',
  'warm modern': 'Warming the materials and natural light…',
  'japandi': 'Balancing calm, wood, and negative space…',
  'zen': 'Settling stillness and material calm…',
  'tropical': 'Bringing in natural texture and open light…',
  'bali': 'Weaving organic texture and sanctuary calm…',
  'nordic': 'Softening with pale wood and hygge warmth…',
  'desert': 'Layering sand tones and sculpted shade…',
  'nature retreat': 'Drawing in raw nature and grounded calm…',
};

String? _atmospherePhase(String atmosphere) {
  final a = atmosphere.toLowerCase();
  for (final entry in _atmosphereFlavor.entries) {
    if (a.contains(entry.key)) return entry.value;
  }
  return null;
}

class _LoadingBubble extends StatefulWidget {
  final int iteration;
  final String atmosphere;
  // Wave 4.9: the image being transformed (cinematic wait presence).
  final File? sourceFile;
  final String? backdropUrl;
  const _LoadingBubble({
    super.key,
    this.iteration = 1,
    this.atmosphere = '',
    this.sourceFile,
    this.backdropUrl,
  });

  @override
  State<_LoadingBubble> createState() => _LoadingBubbleState();
}

class _LoadingBubbleState extends State<_LoadingBubble> with TickerProviderStateMixin {
  late final AnimationController _fadeCtrl;
  late final Animation<double> _fade;
  // Long asymptotic progress: eases toward (not to) ~0.96 over ~80s and never
  // completes — completion only "happens" when the real result replaces this
  // bubble. It therefore never hard-stalls at a fixed value (Wave 4.9.1b /
  // 4.9.1a Task 6: no frozen "did it crash?" feeling).
  late final AnimationController _progressCtrl;
  late final Animation<double> _progress;
  // Subtle continuous breathing on the progress fill so the bar reads as
  // "alive" even while growth is slow. Calm, low-amplitude (Task 4).
  late final AnimationController _breathCtrl;

  late final List<String> _sequence;
  int _phraseIndex = 0;

  @override
  void initState() {
    super.initState();
    _fadeCtrl = AnimationController(vsync: this, duration: const Duration(milliseconds: 300))..forward();
    _fade = CurvedAnimation(parent: _fadeCtrl, curve: Curves.easeOut);

    _progressCtrl = AnimationController(vsync: this, duration: const Duration(seconds: 80))..forward();
    _progress = Tween<double>(begin: 0.04, end: 0.96)
        .animate(CurvedAnimation(parent: _progressCtrl, curve: Curves.easeOut));

    _breathCtrl = AnimationController(
      vsync: this, duration: const Duration(milliseconds: 1700))..repeat(reverse: true);

    // Build the one-shot ordered narrative once. Slot 3 becomes the
    // atmosphere-flavoured beat when the atmosphere is recognised.
    final base = widget.iteration > 1 ? _refinementPhrases : _initialPhrases;
    final seq = List<String>.from(base);
    final flavor = _atmospherePhase(widget.atmosphere);
    if (flavor != null && seq.length > 3) seq[3] = flavor;
    _sequence = seq;

    _advancePhases();
  }

  // Monotonic, non-looping scheduler. Dwell windows widen as generation
  // progresses and carry a small deterministic-ish jitter so the cadence
  // never feels robotic (Task 2). The final phase is never advanced past —
  // it holds until this bubble is removed (success/failure). No modulo, no
  // wrap, no repetition (Task 3).
  void _advancePhases() async {
    // Base dwell per phase (ms); last entry is irrelevant (held).
    const dwell = [3200, 4000, 5200, 6600, 8200, 9000];
    final rnd = Random(widget.iteration * 7919 + _sequence.length);
    for (var i = 0; i < _sequence.length - 1; i++) {
      final jitter = 1.0 + (rnd.nextDouble() - 0.5) * 0.28; // ±14%
      await Future.delayed(
          Duration(milliseconds: (dwell[i] * jitter).round()));
      if (!mounted) return;
      setState(() => _phraseIndex = i + 1);
    }
    // Final phase reached — intentionally do nothing further (held).
  }

  @override
  void dispose() {
    _fadeCtrl.dispose();
    _progressCtrl.dispose();
    _breathCtrl.dispose();
    super.dispose();
  }

  // Backdrop = the image being transformed (cinematic wait presence).
  Widget? _backdrop() {
    if (widget.sourceFile != null) {
      return Image.file(widget.sourceFile!,
          fit: BoxFit.cover,
          width: double.infinity,
          height: double.infinity,
          filterQuality: FilterQuality.medium);
    }
    final u = widget.backdropUrl;
    if (u != null && u.isNotEmpty) {
      return CachedNetworkImage(
        imageUrl: u,
        fit: BoxFit.cover,
        width: double.infinity,
        height: double.infinity,
        placeholder: (_, _) => const ColoredBox(color: AppColors.textPrimary),
        errorWidget: (_, _, _) =>
            const ColoredBox(color: AppColors.textPrimary),
      );
    }
    return null;
  }

  @override
  Widget build(BuildContext context) {
    final h =
        (MediaQuery.sizeOf(context).height * 0.52).clamp(280.0, 560.0);
    final img = _backdrop();
    return FadeTransition(
      opacity: _fade,
      child: Padding(
        padding: const EdgeInsets.only(bottom: 10),
        child: ClipRRect(
          borderRadius: BorderRadius.circular(AppSpacing.radiusCard),
          child: SizedBox(
            height: h,
            width: double.infinity,
            child: RevealCanvas(
              ambientImage: widget.sourceFile != null
                  ? FileImage(widget.sourceFile!)
                  : (widget.backdropUrl != null &&
                          widget.backdropUrl!.isNotEmpty)
                      ? CachedNetworkImageProvider(widget.backdropUrl!)
                      : null,
              ambientBlur: 18,
              ambientDarken: 0.5,
              bottomScrim: true,
              bottomOverlay: Padding(
                padding: const EdgeInsets.fromLTRB(18, 0, 18, 22),
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    _DotsIndicator(),
                    const SizedBox(height: 10),
                    // Fixed transition — outgoing vanishes immediately and
                    // only the incoming fades in (no stacked double-text);
                    // reserved height prevents layout jitter (Wave 4.9 §4).
                    AnimatedSwitcher(
                      duration: const Duration(milliseconds: 360),
                      switchInCurve: Curves.easeOut,
                      switchOutCurve: const Threshold(0),
                      layoutBuilder: (cur, _) =>
                          cur ?? const SizedBox.shrink(),
                      transitionBuilder: (child, anim) =>
                          FadeTransition(opacity: anim, child: child),
                      child: SizedBox(
                        key: ValueKey(_phraseIndex),
                        height: 24,
                        child: Align(
                          alignment: Alignment.centerLeft,
                          child: Text(
                            _sequence[_phraseIndex],
                            maxLines: 1,
                            overflow: TextOverflow.ellipsis,
                            style: Theme.of(context)
                                .textTheme
                                .titleSmall
                                ?.copyWith(
                                  color: AppColors.surface,
                                  fontWeight: FontWeight.w500,
                                ),
                          ),
                        ),
                      ),
                    ),
                    const SizedBox(height: 12),
                    AnimatedBuilder(
                      animation: Listenable.merge([_progress, _breathCtrl]),
                      builder: (_, _) {
                        final breath = 150 + (90 * _breathCtrl.value).round();
                        return SizedBox(
                          width: 200,
                          height: 2,
                          child: ClipRRect(
                            borderRadius: BorderRadius.circular(1),
                            child: Stack(
                              children: [
                                Container(
                                    color: AppColors.surface
                                        .withValues(alpha: 0.22)),
                                FractionallySizedBox(
                                  widthFactor: _progress.value,
                                  child: Container(
                                      color: AppColors.surface
                                          .withAlpha(breath)),
                                ),
                              ],
                            ),
                          ),
                        );
                      },
                    ),
                  ],
                ),
              ),
              child: img ?? const ColoredBox(color: AppColors.textPrimary),
            ),
          ),
        ),
      ),
    );
  }
